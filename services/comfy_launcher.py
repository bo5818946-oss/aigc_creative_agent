"""Start the local ComfyUI server when the studio needs it.

The studio talks to ComfyUI over HTTP, but it does not own that process: the
user may have the desktop app open, a headless server running, or nothing at
all. This module only handles the last case — spawn the configured Python,
point it at a generated model-path config, and wait for ``/system_stats``.

Everything machine-specific (python path, install dir, model dir) comes from
the environment. Nothing is guessed.
"""

from __future__ import annotations

import os
import subprocess
import sys
import time
from dataclasses import dataclass
from pathlib import Path
from tempfile import gettempdir

from config.settings import (
    COMFYUI_HOME,
    COMFYUI_MODELS_DIR,
    COMFYUI_PYTHON,
    COMFYUI_START_TIMEOUT,
    COMFYUI_URL,
)

#: Sub-directories ComfyUI knows how to read. Only ones that exist on disk are
#: written into the config, so a fresh install still starts.
_KNOWN_FOLDERS = (
    "checkpoints",
    "diffusion_models",
    "text_encoders",
    "vae",
    "loras",
    "clip",
    "clip_vision",
    "controlnet",
    "embeddings",
    "upscale_models",
    "style_models",
    "unet",
)

_LOG_PATH = Path(gettempdir()) / "aigc_comfyui.log"


class LaunchError(RuntimeError):
    """ComfyUI could not be started with the configured paths."""


@dataclass(frozen=True)
class LaunchResult:
    ok: bool
    message: str
    pid: int | None = None


def is_configured() -> bool:
    return bool(COMFYUI_PYTHON and COMFYUI_HOME)


def describe_configuration() -> str:
    if is_configured():
        return f"{COMFYUI_PYTHON} · {COMFYUI_HOME}"
    return (
        "还没配置启动路径。在 .env 里设置 AIGC_COMFYUI_PYTHON 与 AIGC_COMFYUI_HOME，"
        "这个按钮才能自己把 ComfyUI 拉起来。"
    )


def build_model_config(models_dir: Path) -> str:
    """A ``--extra-model-paths-config`` body pointing at ``models_dir``."""

    if not models_dir.is_dir():
        raise LaunchError(f"模型目录不存在：{models_dir}")
    existing = {
        item.name for item in models_dir.iterdir() if item.is_dir()
    }
    lines = ["# generated by AIGC Studio", "shared:", f"    base_path: {models_dir.as_posix()}"]
    for name in _KNOWN_FOLDERS:
        if name in existing:
            lines.append(f"    {name}: {name}")
    if len(lines) == 3:
        raise LaunchError(f"{models_dir} 里没有 ComfyUI 认识的模型子目录。")
    return "\n".join(lines) + "\n"


def _write_config(models_dir: Path) -> Path:
    body = build_model_config(models_dir)
    target = Path(gettempdir()) / "aigc_comfyui_model_paths.yaml"
    target.write_text(body, encoding="utf-8")
    return target


def launch(*, timeout: float = COMFYUI_START_TIMEOUT, poll: float = 1.5) -> LaunchResult:
    """Spawn ComfyUI if it is not already answering, then wait for it."""

    from services.comfyui_client import ComfyUIClient, ComfyUIError, ComfyUIUnavailable

    if not is_configured():
        return LaunchResult(False, describe_configuration())

    client = ComfyUIClient(COMFYUI_URL, timeout=3)
    try:
        server = client.server()
        return LaunchResult(True, f"已经在运行：{server.describe()}")
    except (ComfyUIUnavailable, ComfyUIError):
        pass

    home = Path(COMFYUI_HOME)
    python = Path(COMFYUI_PYTHON)
    if not (home / "main.py").is_file():
        raise LaunchError(f"{home} 下没有 main.py")
    if not python.is_file():
        raise LaunchError(f"找不到 Python：{python}")

    config_path = _write_config(Path(COMFYUI_MODELS_DIR)) if COMFYUI_MODELS_DIR else None
    port = COMFYUI_URL.rsplit(":", 1)[-1] or "8188"
    command = [
        str(python),
        "main.py",
        "--listen",
        "127.0.0.1",
        "--port",
        port,
    ]
    if config_path is not None:
        command += ["--extra-model-paths-config", str(config_path)]

    flags = 0
    if sys.platform == "win32":
        flags = subprocess.CREATE_NEW_PROCESS_GROUP | subprocess.CREATE_NO_WINDOW
    log = open(_LOG_PATH, "a", encoding="utf-8")
    try:
        process = subprocess.Popen(
            command,
            cwd=str(home),
            stdout=log,
            stderr=log,
            stdin=subprocess.DEVNULL,
            creationflags=flags,
            start_new_session=sys.platform != "win32",
        )
    except OSError as exc:
        raise LaunchError(f"启动失败：{exc}") from exc
    finally:
        log.close()

    deadline = time.monotonic() + timeout
    while time.monotonic() < deadline:
        if process.poll() is not None:
            tail = _tail(_LOG_PATH)
            raise LaunchError(f"ComfyUI 启动后立刻退出。日志：{tail}")
        try:
            server = client.server()
            return LaunchResult(
                True,
                f"已启动：{server.describe()}",
                pid=process.pid,
            )
        except (ComfyUIUnavailable, ComfyUIError):
            time.sleep(poll)

    raise LaunchError(
        f"等了 {timeout:g} 秒 ComfyUI 还没起来，日志：{_tail(_LOG_PATH)}"
    )


def _tail(path: Path, limit: int = 600) -> str:
    try:
        text = path.read_text(encoding="utf-8", errors="replace")
    except OSError:
        return "（没有日志）"
    return text[-limit:].strip() or "（日志为空）"
